# ---- small readers (every read is tolerant: a missing or broken file is None, never 0) --------------------------------------------

def read_json(p, default=None):
    try:
        return json.loads(Path(p).read_text())
    except (OSError, ValueError):
        return default


def read_jsonl_gz(p):
    try:
        with gzip.open(p, 'rt') as f:
            return [json.loads(line) for line in f if line.strip()]
    except (OSError, ValueError):
        return None


def under_root(rel, root):
    """root/rel when it stays inside root (a registry path never leaves the project root), else None."""
    p = (Path(root) / rel).resolve()
    try:
        p.relative_to(Path(root).resolve())
    except ValueError:
        return None
    return p


def short(p, root):
    try:
        return str(Path(p).relative_to(root))
    except ValueError:
        return str(p)


def mtime_utc(p):
    try:
        return datetime.datetime.fromtimestamp(Path(p).stat().st_mtime, datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    except OSError:
        return None


def work_key(r):
    """One key per work: the OpenAlex id, else the DOI, else the normalised title (the 2026-11-10 audit's rule)."""
    return r.get('oa') or (r.get('doi') or '').lower() or re.sub(r'[^a-z0-9]+', ' ', (r.get('title') or '').lower()).strip()


# ---- the cohort and the charters -------------------------------------------------------------------------------------------------

def load_roster(path):
    try:
        with open(path, newline='') as f:
            return list(csv.DictReader(f, delimiter='\t'))
    except OSError:
        return []


def load_charters(directory):
    """{key: {name, short, status, openalex}} of schools/*.toml (TEMPLATE excluded)."""
    out = {}
    for p in sorted(Path(directory).glob('*.toml')):
        if p.stem == 'TEMPLATE':
            continue
        try:
            t = tomllib.loads(p.read_text())
        except (OSError, ValueError):
            continue
        out[t.get('key') or p.stem] = dict(name=t.get('name'), short=t.get('short'), status=t.get('status'),
                                           openalex=((t.get('ids') or {}).get('openalex') or t.get('openalex') or [None])[0])
    return out


def universe(roster, charters, registry, top, only=None):
    """Rows of the table: every charter school plus every cohort row of rank <= top (keyed by the registry's `inventory` map)."""
    by_oa = {c['openalex']: k for k, c in charters.items() if c.get('openalex')}
    inv = registry.get('inventory') or {}
    inv_by_site = {v.get('site_id'): k for k, v in inv.items()}
    rows, seen = [], set()
    for r in roster:
        if r.get('in_cohort') != 'true':
            continue
        key = by_oa.get(r.get('openalex_id')) or inv_by_site.get(r.get('site_id'))
        low = int(r['rank_low']) if (r.get('rank_low') or '').isdigit() else None
        if key is None and not (low is not None and low <= top):
            continue
        key = key or r['site_id']
        rows.append(dict(key=key, rank=r.get('cohort_rank'), rank_low=low, university=r.get('name'), country=r.get('country'),
                         site_id=r.get('site_id'), registered=key in charters or key in inv))
        seen.add(key)
    for k, c in charters.items():
        if k not in seen:
            rows.append(dict(key=k, rank='', rank_low=None, university=c.get('name'), country='', site_id='', registered=True))
    if only:
        rows = [r for r in rows if r['key'] in only]
    return sorted(rows, key=lambda r: (r['rank_low'] is None, r['rank_low'] or 0, r['university'] or r['key']))


# ---- frozen release --------------------------------------------------------------------------------------------------------------

def frozen_release(releases):
    """The newest frozen release: releases/latest, else the newest releases/<date>/ holding a MANIFEST.json. None when there is none."""
    releases = Path(releases)
    cands = [releases / 'latest']
    try:
        cands += sorted((d for d in releases.iterdir() if d.is_dir() and d.name != 'latest'), key=lambda d: d.name, reverse=True)
    except OSError:
        pass
    for d in cands:
        m = read_json(d / 'MANIFEST.json')
        if isinstance(m, dict) and m.get('counts'):
            return dict(id=m.get('release') or d.resolve().name, dir=d.resolve(), created=m.get('created'), counts=m['counts'])
    return None


def frozen_school(rel, key):
    """Counts of the school in the frozen release (MANIFEST counts, copies.json summary, students.json lists); None when it is not counted."""
    c = (rel or {}).get('counts', {}).get(key)
    if not c:
        return None
    h = rel['dir'] / 'hierarchy' / key
    cp = (read_json(h / 'copies.json') or {}).get('summary') or {}
    st = read_json(h / 'students.json')
    pairs = sum(len(v) for v in st.values()) if isinstance(st, dict) else None
    files = [short(rel['dir'] / 'MANIFEST.json', P.ROOT)] + [short(h / n, P.ROOT) for n in ('copies.json', 'students.json')]
    return dict(c, distinct=cp.get('lab_papers'), local=cp.get('local'), local_share=cp.get('local_share'), counted_at=cp.get('counted_at'),
                member_pairs=pairs, files=files)


# ---- isolated packages -----------------------------------------------------------------------------------------------------------

def package_stats(d):
    """Distinct works (not rows), PI-paper relations, PIs with papers, students and lab-student pairs of a package directory; None if unreadable."""
    d = Path(d)
    rows = read_jsonl_gz(d / 'lab_papers.jsonl.gz')
    pis = read_json(d / 'pis.json')
    if rows is None or pis is None:
        return None
    pis = pis if isinstance(pis, list) else pis.get('pis', [])
    keys = {work_key(r) for r in rows}
    rel = {(r.get('pi'), work_key(r)) for r in rows}
    st = read_json(d / 'students.json')
    st = st if isinstance(st, dict) else {}
    entries = [m for lst in st.values() for m in (lst if isinstance(lst, list) else [])]
    rep = read_json(d / 'report.json') or {}
    c = rep.get('counts') or rep
    people = {m.get('person') or m.get('name') for m in entries}
    return dict(built_at=rep.get('builtAt'), pis=len({p.get('pi') for p in pis}), pis_with_papers=len({r.get('pi') for r in rows}),
                relations=len(rel), distinct=len(keys), rows=len(rows),
                students=c.get('students') if isinstance(c.get('students'), int) else (len(people) if entries else None),
                lab_student_pairs=c.get('lab_student_pairs') if isinstance(c.get('lab_student_pairs'), int) else (len(entries) if entries else None),
                member_pairs=len(entries) if st else None)


def resolve_package(entry, root):
    """(directory, flags): the first of entry['candidates'] (newest first), then entry['path'], that holds a built package."""
    flags, tried = [], []
    for rel in list(entry.get('candidates') or []) + ([entry['path']] if entry.get('path') else []):
        d = under_root(rel, root)
        if d is None:
            flags.append(f'registry path {rel!r} leaves the project root; ignored')
            continue
        if (d / 'lab_papers.jsonl.gz').exists() and (d / 'pis.json').exists():
            if tried:
                flags.append('newer candidate not built yet (' + ', '.join(tried) + '); latest built package used')
            return d, flags
        tried.append(rel)
    if tried:
        flags.append('registered package not found: ' + ', '.join(tried))
    return None, flags


# ---- gates -----------------------------------------------------------------------------------------------------------------------

def live_gate(key, stage):
    """stage_gate.evaluate in-process: read-only (it never writes; --run and --record are what write)."""
    import stage_gate as G
    r = G.evaluate(key, stage)
    return dict(gate=r['gate'], open=r['open'])


def recorded_gate(key, stage, hierarchy=None):
    """The last recorded hierarchy/<key>/reports/stage-<n>-gate.json: dict(gate, open, at) or None."""
    d = read_json(Path(hierarchy or P.HIERARCHY) / key / 'reports' / f'stage-{stage}-gate.json')
    if not isinstance(d, dict) or not isinstance(d.get('result'), dict):
        return None
    return dict(gate=d['result'].get('gate'), open=d['result'].get('open'), at=(d.get('at') or '')[:10])


def gate_cell(g):
    if not g:
        return ''
    cell = g['gate'] + (f" ({g['open']} open)" if g.get('open') else '')
    return f"recorded {g['at']}: {cell}" if g.get('at') else cell


def gates_for(key, mode, live_fn=live_gate, recorded_fn=recorded_gate, has_charter=True):
    """-> (cells {stage: dict|None}, basis, flags). live falls back per stage to the recorded file when the in-process call raises."""
    if mode == 'off' or not has_charter:
        return {n: None for n in STAGES}, ('no charter' if not has_charter else 'off'), ['no charter: gates 0-10 do not apply yet'] if not has_charter else []
    out, flags, how = {}, [], set()
    for n in STAGES:
        g = None
        if mode == 'live':
            try:
                g = dict(live_fn(key, n), at=None)
                how.add('live')
            except (Exception, SystemExit) as e:   # noqa: BLE001  (a gate that cannot run in-process must not stop the table)
                flags.append(f'gate {n}: in-process call failed ({type(e).__name__}: {str(e)[:80]})')
        if g is None:
            g = recorded_fn(key, n)
            if g:
                how.add('recorded')
        out[n] = g
    return out, '+'.join(sorted(how)) or 'none', flags


def gates_left(cells):
    """Every stage that is not pass: 'N' fail, 'Nw' waived, 'N?' unknown (no result)."""
    left = []
    for n in STAGES:
        g = cells.get(n)
        left.append(f'{n}?' if not g else f'{n}w' if g['gate'] == 'waived' else None if g['gate'] == 'pass' else str(n))
    return ','.join(x for x in left if x)


# ---- git, queue, collectors, ids -------------------------------------------------------------------------------------------------

def git(repo, *args):
    try:
        r = subprocess.run(['git', '-C', str(repo), *args], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def branch_tokens(name):
    return set(re.split(r'[^a-z0-9]+', name.lower()))


def git_state(repo, keys, registry_packages, main='main'):
    """{key: dict(last_main, branches [(name, sha, date, ahead)])}: unlanded branches (not ancestors of main) whose name carries the school key
    as a token (or are listed in the registry entry's `branches`), and the last commit on main touching hierarchy/<key> or schools/<key>.toml."""
    out = {k: dict(last_main='', branches=[]) for k in keys}
    refs = git(repo, 'for-each-ref', '--no-merged', main, '--format=%(refname:short)|%(objectname:short)|%(committerdate:iso-strict)', 'refs/heads') or ''
    unmerged = []
    for line in refs.splitlines():
        name, sha, date = (line.split('|') + ['', ''])[:3]
        if name and name != main:
            unmerged.append((name, sha, date))
    for k in keys:
        extra = set((registry_packages.get(k) or {}).get('branches') or [])
        for name, sha, date in unmerged:
            if k in branch_tokens(name) or name in extra:
                n = git(repo, 'rev-list', '--count', f'{main}..{name}')
                out[k]['branches'].append((name, sha, date, int(n) if n and n.isdigit() else None))
        out[k]['branches'].sort(key=lambda b: b[2], reverse=True)
        c = git(repo, 'log', main, '-1', '--format=%h %cI %s', '--', f'hierarchy/{k}', f'schools/{k}.toml')
        out[k]['last_main'] = (c or '')[:140]
    return out


def queue_state(tasks, at=None):
    """{school: dict(open, live [(id, holder)], stale [id], blocked [id])} from the work-queue records (tools/work_queue.py semantics)."""
    import work_queue as W
    out = {}
    for t in tasks:
        s = t.get('school')
        if not s:
            continue
        o = out.setdefault(s, dict(open=[], live=[], stale=[], blocked=[]))
        st = W.state(t) if t.get('status') in W.LIVE_STATUSES else t.get('status')
        if st in W.LIVE_STATUSES:
            o['live'].append((t['id'], t.get('session') or ''))
        elif st == 'stale':
            o['stale'].append(t['id'])
        elif st == 'open':
            o['open'].append(t['id'])
        elif st == 'blocked':
            o['blocked'].append(t['id'])
    return out


def ids_state(ids_dir):
    """The global ID registry's sha256 and the live coadvising holds, from IDS-REPORT.json (the ids stage is never run here)."""
    ids_dir = Path(ids_dir)
    reg = ids_dir / 'registry.sqlite'
    h = None
    if reg.exists():
        sha = hashlib.sha256()
        with open(reg, 'rb') as f:
            for chunk in iter(lambda: f.read(1 << 22), b''):
                sha.update(chunk)
        h = sha.hexdigest()
    rep = read_json(ids_dir / 'IDS-REPORT.json') or {}
    holds = rep.get('coadvising_holds_skipped')
    return dict(registry_sha256=h, registry_mtime=mtime_utc(reg), report_at=rep.get('at'),
                coadvising_holds=len(holds) if isinstance(holds, list) else None,
                holds_note=None if isinstance(holds, list) else 'IDS-REPORT.json has no coadvising_holds_skipped (the report predates the field; the live count is unknown)')


def accuracy_cell(key, code):
    d = read_json(Path(code) / 'accuracy' / f'summary-{key}.json')
    if not isinstance(d, dict):
        return ''

    def p(k):
        v = (d.get(k) or {}).get('p')
        return f'{v:.3f}' if isinstance(v, (int, float)) else '?'
    return f"lab {p('lab_precision_uniform')} student {p('student_precision_uniform')} coverage {p('lab_coverage')} (n={d.get('n_verdicts')}, {d.get('date') or '?'})"


# ---- one row ---------------------------------------------------------------------------------------------------------------------

def build_row(u, ctx):
    key = u['key']
    root, reg = ctx['root'], ctx['registry']
    ch = ctx['charters'].get(key)
    pk = (reg.get('packages') or {}).get(key) or {}
    fz = frozen_school(ctx['release'], key)
    flags, srcs = [], []
    if not u['registered']:
        flags.append('no charter and not in the registry inventory map: key taken from the roster site_id')
    row = dict.fromkeys(COLUMNS, '')
    row.update(rank=u['rank'], school=key, university=u['university'], country=u['country'], charter_status=(ch or {}).get('status') or 'no charter',
               state='built' if fz else 'staged')
    # (2) frozen release
    if fz:
        row.update(frozen_release=ctx['release']['id'], frozen_PIs=fz.get('pis'), frozen_lab_paper_rows=fz.get('lab_papers'), frozen_distinct_papers=fz.get('distinct'),
                   frozen_students=fz.get('students'), frozen_lab_student_pairs=fz.get('lab_student_pairs'), frozen_pis_with_papers=fz.get('pis_with_lab_papers'))
        srcs += fz['files']
        if fz.get('distinct') is None:
            flags.append('frozen distinct papers unreadable (copies.json summary missing)')
    # (3) package
    pkg = None
    if pk:
        d, f = resolve_package(pk, root)
        flags += f
        pkg = package_stats(d) if d else None
        if d and pkg is None:
            flags.append(f'package {short(d, root)} unreadable')
        if pkg:
            row.update(package_path=short(d, root), package_built_at=pkg['built_at'] or '', package_pis=pkg['pis'], package_pis_with_papers=pkg['pis_with_papers'],
                       package_pi_paper_relations=pkg['relations'], package_distinct_works=pkg['distinct'], package_students=pkg['students'],
                       package_lab_student_pairs=pkg['lab_student_pairs'])
            srcs.append(short(d, root) + '/{lab_papers.jsonl.gz,pis.json,students.json,report.json}')
            if not pkg['built_at']:
                flags.append('package report.json has no builtAt; as-of is the file time')
        sp = pk.get('split')
        if sp:
            row.update(source_backed_distinct=sp.get('source_backed_distinct'), all_kept_distinct=sp.get('all_kept_distinct'), split_basis=sp.get('source') or '')
            flags.append(f"source-backed/all-kept split typed in the registry from {sp.get('source') or '?'} ({sp.get('as_of') or 'undated'}), not recomputed here")
    # headline counts: the registered package when there is one, else the frozen release (labelled; rows and works stay apart)
    if pkg:
        basis = pk.get('basis') or 'registered isolated package'
        row.update(PIs=pkg['pis'], known_student_lab_pairs=pkg['lab_student_pairs'], known_member_lab_pairs=pkg['member_pairs'], papers=pkg['distinct'],
                   counts_basis=f'{basis}; distinct works, not rows', data_as_of_utc=pkg['built_at'] or mtime_utc(d / 'lab_papers.jsonl.gz') or '')
    elif fz:
        row.update(PIs=fz.get('pis'), known_student_lab_pairs=fz.get('lab_student_pairs'), known_member_lab_pairs=fz.get('member_pairs'), papers=fz.get('distinct'),
                   counts_basis=f"frozen release {ctx['release']['id']}: distinct papers from copies.json summary; PIs and pairs from MANIFEST counts; member pairs = sum of students.json lists",
                   data_as_of_utc=fz.get('builtAt') or '')
    elif (reg.get('carried') or {}).get(key, {}).get('PIs') is not None:
        iv = reg['carried'][key]
        row.update(PIs=iv.get('PIs'), known_student_lab_pairs=iv.get('known_student_lab_pairs'), known_member_lab_pairs=iv.get('known_member_lab_pairs'),
                   counts_basis='counts carried in the registry (inventory only); no paper package', data_as_of_utc=iv.get('as_of') or '')
        srcs += [short(P.data(REGISTRY_NAME), root), iv.get('source') or '']
        flags.append(f"PIs/pairs carried from the registry `carried` entry ({iv.get('as_of') or 'undated'}), not re-derived here")
    else:
        flags.append('no frozen release count and no registered package: counts unknown')
    # websites (the register's `website` coverage, when the school has one)
    reg_w = read_json(Path(ctx['data'](key, 'lab-websites.json')))
    if isinstance(reg_w, dict) and isinstance(reg_w.get('labs'), list):
        row['websites'] = sum(1 for x in reg_w['labs'] if x.get('coverage') == 'website')
        srcs.append(short(ctx['data'](key, 'lab-websites.json'), root))
    elif (reg.get('carried') or {}).get(key, {}).get('websites') is not None:
        row['websites'] = reg['carried'][key]['websites']
        srcs.append((reg['carried'][key].get('source') or '').split(' (')[0])
        flags.append(f"websites carried from the registry `carried` entry ({reg['carried'][key].get('as_of') or 'undated'}), not re-derived")
    else:
        flags.append('websites blank: no lab-websites.json register for this school')
    # admission and target
    target = ctx['target']
    n = row['papers'] if row['papers'] != '' else None
    if fz:
        row['admission_status'] = f"in frozen release {ctx['release']['id']}"
        if pkg:
            row['admission_status'] += f"; registered package ({pk.get('basis') or 'package'}) NOT admitted"
        row['target_basis'] = 'distinct papers, frozen' if not pkg else 'distinct works; frozen vs package in separate columns'
        d_f = fz.get('distinct')
        row['target_status'] = ('' if d_f is None else f'met in frozen release: {d_f} distinct >= {target}' if d_f >= target else f'below {target} in frozen release ({d_f} distinct)')
    else:
        row['admission_status'] = 'not admitted'
        row['target_basis'] = 'distinct works, unadmitted package' if pkg else ''
        if n is not None:
            row['target_status'] = f'package meets {target} ({n}) but NOT admitted: gates not all pass' if n >= target else f'below {target} ({n} distinct); not admitted'
    sb = row['source_backed_distinct']
    if pk.get('split') and isinstance(sb, int):
        row['target_status'] = (f"source-backed {sb} distinct ({'meets' if sb >= target else 'below'} {target}) / all kept {row['all_kept_distinct']} distinct; NOT admitted")
        row['target_basis'] = 'source-backed vs all kept (reviewed split)'
    # (4) gates
    cells, basis, gflags = gates_for(key, ctx['gates'], ctx['live_fn'], ctx['recorded_fn'], has_charter=ch is not None)
    flags += gflags
    for s in STAGES:
        row[f'gate{s}'] = gate_cell(cells[s])
    row['gates_basis'] = basis
    row['gates_left'] = gates_left(cells) if ch is not None else ','.join(map(str, STAGES))
    if 'recorded' in basis:
        flags.append('some gates are recorded results, not live (see the `recorded <date>` cells)')
    ex = read_json(Path(ctx['data'](key, 'gate-exceptions.json')), {}) or {}
    row['gate_exceptions'] = '; '.join(f"{s}: {str((v or {}).get('reason') or '')[:80]}" for s, v in sorted(ex.items())) if isinstance(ex, dict) else ''
    # (5) copies and the loop
    cj = None
    for label, p in (('registered counter', pk.get('copies_counter') and under_root(pk['copies_counter'], root)),
                     ('hierarchy copies.json', Path(ctx['data'](key, 'copies.json')))):
        cj = (read_json(p) or {}).get('summary') if p else None
        if cj and cj.get('lab_papers'):
            row['copies_source'] = f"{short(p, root)} (counted {cj.get('counted_at') or 'undated'})"
            srcs.append(short(p, root))
            break
        cj = None
    if cj is None and fz and fz.get('distinct'):
        cj = dict(lab_papers=fz['distinct'], local=fz.get('local'), local_share=fz.get('local_share'), counted_at=fz.get('counted_at'))
        row['copies_source'] = f"frozen release {ctx['release']['id']} copies.json (counted {fz.get('counted_at') or 'undated'})"
    if cj:
        row.update(copies_local=cj.get('local') if cj.get('local') is not None else '', copies_total=cj.get('lab_papers'),
                   copies_share=cj.get('local_share') if cj.get('local_share') is not None else '')
        if row['papers'] != '' and cj.get('lab_papers') != row['papers']:
            flags.append(f"copies base ({cj.get('lab_papers')}) differs from the headline distinct papers ({row['papers']})")
    elif ch is not None:
        flags.append('copies not measured: no copies.json, no registered counter, not in the frozen release')
    lp = (ctx['loops'] or {}).get(key)
    if lp:
        row.update(loop_phase=lp.get('phase') or '', loop_rounds=lp.get('rounds') if lp.get('rounds') is not None else '',
                   loop_attempts_24h=lp.get('attempts_24h', ''), loop_downloads_24h=lp.get('downloads_24h', ''), loop_as_of=ctx['loops_at'] or '')
    row['accuracy'] = accuracy_cell(key, ctx['code'])
    # (6) git
    g = ctx['git'].get(key) or dict(last_main='', branches=[])
    row['last_main_commit'] = g['last_main'] or ''
    if g['branches']:
        name, sha, _d, ahead = g['branches'][0]
        row['latest_work_branch'] = f'{name} @ {sha}'
        row['branch_on_main'] = f'NO: {ahead} commits ahead of main' if ahead is not None else 'NO'
        shown = g['branches'][:BRANCHES_SHOWN]
        row['unlanded_branches'] = '; '.join(f'{b[0]} (+{b[3]})' for b in shown) + (f' ... and {len(g["branches"]) - len(shown)} more' if len(g['branches']) > len(shown) else '')
    else:
        row['latest_work_branch'] = 'main (no unlanded branch)'
        row['branch_on_main'] = 'yes'
    # (7) tasks
    q = ctx['queue'].get(key) or dict(open=[], live=[], stale=[], blocked=[])
    row['tasks_live'] = '; '.join(f'{i} ({h})' for i, h in q['live'])
    row['tasks_stale'] = ' '.join(q['stale'])
    row['task_ids'] = ' '.join(sorted(set(i for i, _ in q['live']) | set(q['stale']) | set(q['open']) | set(q['blocked'])))
    # derived blockers and the registry's reviewed next step
    bl = []
    if row['gates_left']:
        bl.append(f"gates not pass: {row['gates_left']}")
    if g['branches']:
        bl.append(f"{len(g['branches'])} unlanded branch(es)")
    if q['stale']:
        bl.append(f"stale claims: {' '.join(q['stale'])}")
    if q['blocked']:
        bl.append(f"blocked tasks: {' '.join(q['blocked'])}")
    row['blockers'] = '; '.join(bl)
    row['next_step'] = pk.get('next_step') or ''
    row['source_files'] = '; '.join(dict.fromkeys(srcs))
    if not row['data_as_of_utc']:
        flags.append('data_as_of_utc blank: no counts source')
    row['flags'] = ' | '.join(dict.fromkeys(flags))
    for c in INT_FIELDS:
        if row[c] is None:
            row[c] = ''
    return {k: ('' if v is None else v) for k, v in row.items()}


