def sensitivity_partial(pr):
    L = ['## 9. Sensitivity: excluding harvard, jhu and washu\n',
         'The three partial schools carry 3-6% full-text coverage, so the AI outcomes barely move; the gras split changes composition (Harvard is the only 11-50 school besides Georgia Tech; JHU and WashU leave the 51-300 band). Primary-definition contrasts, post - pre difference, ALL against EXCL_PARTIAL:\n']
    p = pr[(pr.family == 'primary') & (pr.contrast == 'post_minus_pre')]
    a = p[p.scope == 'ALL'].set_index(['split', 'outcome', 'g1', 'g2'])
    b = p[p.scope == 'EXCL_PARTIAL'].set_index(['split', 'outcome', 'g1', 'g2'])
    j = a[['est', 'lo', 'hi']].join(b[['est', 'lo', 'hi', 'p']], rsuffix='_x').reset_index()
    j['same_sign'] = np.sign(j.est) == np.sign(j.est_x)
    j['x_excl'] = (j.lo_x > 0) | (j.hi_x < 0)
    j['a_excl'] = (j.lo > 0) | (j.hi < 0)
    L.append(f'- {len(j)} contrasts; the point estimate keeps its sign in {int(j.same_sign.sum())}; the interval excludes zero in {int(j.a_excl.sum())} with the partial schools and in {int(j.x_excl.sum())} without them; '
             f'the exclusion status changes in {int((j.a_excl != j.x_excl).sum())}.')
    ch = j[j.a_excl != j.x_excl]
    if len(ch):
        L.append('- Contrasts whose interval status changes:\n')
        L.append(md(pd.DataFrame([{'split': r.split, 'outcome': LABEL[r.outcome], 'difference': f'{nm(r.g1)} - {nm(r.g2)}', 'all 12': fci(r.outcome, r.est, r.lo, r.hi),
                                  'excl. partial': fci(r.outcome, r.est_x, r.lo_x, r.hi_x)} for r in ch.itertuples()])))
    return '\n'.join(L) + '\n'


