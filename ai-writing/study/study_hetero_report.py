LABEL = {'heavy_main': 'Heavy-AI papers, main body (%)', 'heavy_main_appendix': 'Heavy-AI papers, main + appendix (%)', 'abs_flag': 'Abstract flagged (%)',
         'within_lab': 'Within-lab distance', 'lab_to_school': 'Lab-to-school distance'}
PCT = {'heavy_main', 'heavy_main_appendix', 'abs_flag'}
NAMES = {'early': 'early (<10 y)', 'mid': 'mid (10-20 y)', 'senior': 'senior (>20 y)', 'pi_led': 'PI-led', 'student_led': 'student-led', 'other': 'other',
         'theory': 'theory', 'systems': 'systems', 'ml_ai': 'ML/AI', 'top10': 'GRAS top 10', 'r11_50': 'GRAS 11-50', 'r51_300': 'GRAS 51-300'}


def nm(g):
    return NAMES.get(g, g)


def scale(o):
    return 100.0 if o in PCT else 1.0


def fv(o, x, signed=False):
    if x is None or not np.isfinite(x):
        return 'n/a'
    return f'{x * scale(o):+.2f}' if signed and o in PCT else (f'{x * scale(o):.2f}' if o in PCT else (f'{x:+.4f}' if signed else f'{x:.4f}'))


def fci(o, e, lo, hi):
    return f'{fv(o, e, True)} [{fv(o, lo, True)}, {fv(o, hi, True)}]'


def pf(p):
    return 'n/a' if not np.isfinite(p) else ('<0.001' if p < 0.001 else f'{p:.3f}')


def md(df):
    if df.empty:
        return '(none)\n'
    h = '| ' + ' | '.join(df.columns) + ' |\n|' + '|'.join('---' for _ in df.columns) + '|\n'
    return h + ''.join('| ' + ' | '.join(str(x) for x in r) + ' |\n' for r in df.itertuples(index=False))


def fig_split(ser, split, groups, out, scope='ALL'):
    s = ser[(ser.split == split) & (ser.scope == scope)]
    fig, ax = plt.subplots(1, 5, figsize=(15, 3.0))
    for a, o in zip(ax, H.OUTCOMES):
        for i, g in enumerate(groups):
            d = s[(s.outcome == o) & (s.group == g)].sort_values('year')
            if d.empty:
                continue
            k = scale(o)
            a.plot(d.year, k * d.est, color=COL[i % 4], lw=1.5, marker='o', ms=2.5, label=nm(g))
            a.fill_between(d.year, k * d.lo, k * d.hi, color=COL[i % 4], alpha=0.15, lw=0)
        a.axvline(2022.92, color=MUTED, lw=0.8, ls=':')
        a.set_xticks(range(2016, 2026, 3))
        a.set_title(LABEL[o], fontsize=8)
    ax[0].legend(frameon=False, fontsize=7)
    fig.suptitle(f'{split}: year by year, 95% lab-cluster bootstrap bands ({scope.replace("_", " ").lower()} schools); dotted line = ChatGPT', fontsize=8.5, color=INK)
    fig.tight_layout()
    fig.savefig(out / f'fig_h_{split.replace(":", "_")}.png', dpi=150)
    plt.close(fig)


def fig_forest(pr, out):
    f = pr[pr.in_family].copy()
    f['lab'] = f.split + ': ' + f.g1.map(nm) + ' - ' + f.g2.map(nm)
    fig, ax = plt.subplots(1, 5, figsize=(15, 8), sharey=True)
    order = list(dict.fromkeys(f.lab))
    for a, o in zip(ax, H.OUTCOMES):
        d = f[f.outcome == o].set_index('lab').reindex(order)
        y = np.arange(len(order))[::-1]
        k = scale(o)
        c = np.where(d.p_holm < 0.05, ORANGE, np.where(d.p_bh < 0.05, PURPLE, MUTED))
        a.hlines(y, k * d.lo, k * d.hi, color=c, lw=1.3)
        a.scatter(k * d.est, y, color=c, s=14, zorder=3)
        a.axvline(0, color=INK, lw=0.7)
        a.set_title(LABEL[o], fontsize=8)
    ax[0].set_yticks(np.arange(len(order))[::-1])
    ax[0].set_yticklabels(order, fontsize=6.5)
    fig.suptitle('Difference between groups in the post-minus-pre change (75 primary contrasts); orange = survives Holm, purple = BH only, grey = neither', fontsize=9, color=INK)
    fig.tight_layout()
    fig.savefig(out / 'fig_h_forest.png', dpi=150)
    plt.close(fig)


def group_table(eff, split, scope='ALL'):
    e = eff[(eff.split == split) & (eff.scope == scope)]
    rows = []
    for o in H.OUTCOMES:
        for g in e[e.outcome == o].group.unique():
            a = e[(e.outcome == o) & (e.group == g)].set_index('contrast')
            p, q = a.loc['post_minus_pre'], a.loc['placebo_2019_21_minus_2016_18']
            rows.append({'outcome': LABEL[o], 'group': nm(g), 'pre': fv(o, p.pre), 'post': fv(o, p.post), 'post - pre [95% CI]': fci(o, p.est, p.lo, p.hi),
                         'placebo [95% CI]': fci(o, q.est, q.lo, q.hi)})
    return pd.DataFrame(rows)


def pair_table(pr, split, scope='ALL'):
    p = pr[(pr.split == split) & (pr.scope == scope) & (pr.contrast == 'post_minus_pre')]
    rows = []
    for _, r in p.iterrows():
        row = {'outcome': LABEL[r.outcome], 'difference': f'{nm(r.g1)} - {nm(r.g2)}', 'DiD [95% CI]': fci(r.outcome, r.est, r.lo, r.hi), 'p': pf(r.p)}
        if r.in_family:
            row.update({'Holm': pf(r.p_holm), 'BH': pf(r.p_bh)})
        row['placebo DiD [95% CI]'] = fci(r.outcome, r.placebo_est, r.placebo_lo, r.placebo_hi)
        rows.append(row)
    return pd.DataFrame(rows)


