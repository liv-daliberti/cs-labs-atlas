def field_validation(work, ser):
    L = []
    hp = pd.read_parquet(work / 'hetero_papers.parquet', columns=['k', 'field', 'field_alt', 'field_source', 'led'])
    L.append('Source of the field label (lab-paper rows):\n')
    L.append(md(hp.groupby(['field_source', 'field']).size().unstack(fill_value=0).reset_index()))
    vm = pd.read_csv(work / 'venue_map.csv')
    L.append(f'Venue map: {len(vm)} reviewed CS venues; area by venue count: {vm.area.fillna("none").value_counts().to_dict()}; by lab-paper count: '
             f'{vm.assign(area=vm.area.fillna("none")).groupby("area").lab_papers.sum().to_dict()}. "ambiguous"/"none" venues (e.g. Lecture Notes in Computer Science, Communications of the ACM) are classified by topic.\n')
    r1 = work.parent / 'field_handcheck_round1.csv'
    if r1.exists():
        h = pd.read_csv(r1)
        ok = h.my_label == h.assigned
        L.append(f'**Hand check, round 1** (30 lab papers, stratified draw 7/8/8/7 by assigned field, numpy seed {T.ROUND1_SEED}; the analyst labelled each from title and venue): '
                 f'{int(ok.sum())} of 30 agreed ({100 * ok.mean():.0f}%) with the first version of the rules. Failures: crypto and quantum-information topics sent to theory, control/physics papers whose OpenAlex topic sits in a CS subfield, '
                 'education-analytics papers sent to ML/AI, and a 3D-vision paper filed under OpenAlex Engineering. The final rules add: cryptography topics to systems (crypto venues stay theory), '
                 'a topic rule sending quantum, education/learning-analytics, synchronisation, dynamical and physics topics to other, and drop the subfield default for theory.\n')
    hc = work.parent / 'field_handcheck.csv'
    if hc.exists():
        h = pd.read_csv(hc)
        ok = h.my_label == h.assigned
        L.append(f'**Hand check, round 2, final rules** ({len(h)} lab papers, fresh draw, numpy seed {T.HANDCHECK_SEED}; `field_handcheck.csv`): '
                 f'**{int(ok.sum())} of {len(h)} agree ({100 * ok.mean():.0f}%)**. By assigned field:\n')
        t = h.assign(ok=ok).groupby('assigned').agg(n=('ok', 'size'), agree=('ok', 'sum')).reset_index()
        L.append(md(t))
        bad = h[~ok]
        if len(bad):
            L.append('Disagreements:\n')
            L.append(md(bad[['assigned', 'my_label', 'field_source', 'venue', 'title']].assign(title=lambda x: x.title.str.slice(0, 80), venue=lambda x: x.venue.fillna('').str.slice(0, 40))))
    else:
        L.append('(round 2 hand check file not present)\n')
    hl = work.parent / 'led_handcheck.csv'
    if hl.exists():
        h = pd.read_csv(hl)
        ok = h.my_label == h.assigned
        L.append(f'**Hand check of the led split** ({len(h)} lab papers, seed {T.HANDCHECK_SEED}): {int(ok.sum())} of {len(h)} agree.\n')
    return '\n'.join(L)


def caveats(work):
    return '''## 11. Caveats

- **No claim about who uses AI.** The heavy-AI share is a lower bound of AI-flagged passages (the detector misses some unseen generators); groups can differ in detector sensitivity, in language background, or in how much they polish text with tools that are not "writing by AI".
- **Group differences are not causal.** Seniority, student-led work, field and school rank co-vary (senior PIs sit in top schools, ML/AI papers are mostly student-led). Each split is marginal; no joint model is fitted here.
- **Career age is a proxy.** First publication year comes from OpenAlex author profiles that can merge or split people; PIs without a reviewed profile fall back to the extraction ids; a lateral hire's career age is not their time at the school (the appointment-start variant covers PIs with a dated period only).
- **Student-led is name matching** inside each lab's roster; unlisted students land in "other". PI-last is the CS norm, so "PI-led" (PI first) is a small, atypical set (mostly theory and single-author work).
- **Field is a rule-based map**, hand-checked on 30 papers; robotics is "other" in the primary reading.
- **Prestige has 12 schools**, three bands; the three partial schools (harvard, jhu, washu) have 3-6% full-text coverage, so their AI outcomes rest on few papers.
- **Embedding outcomes** use one model (SPECTER2 proximity) and lab-years with >= 5 (or >= 3) papers; the lab-to-school pool is not resampled.
'''


