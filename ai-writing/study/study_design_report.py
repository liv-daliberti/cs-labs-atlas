"""Headline tables of the three design layers as markdown (designs/headline.md), written from the CSV tables so no number is typed by hand. DESIGNS.md quotes them.
usage: study_design_report.py [--id 2026-11-08]
"""
import argparse

import pandas as pd

import study_common as C

SHARE = {'heavy_main', 'abs_flag'}


def fmt(r, k=100.0, nd=1):
    if r is None or (isinstance(r, float) and pd.isna(r)):
        return 'n/a'
    return f'{k * r.est:.{nd}f} [{k * r.lo:.{nd}f}, {k * r.hi:.{nd}f}]'


def pick(t, **kw):
    q = t
    for a, b in kw.items():
        q = q[q[a] == b]
    return q.iloc[0] if len(q) else None


def design1(T):
    t = pd.read_csv(T / 'panel_fe.csv')
    ev = pd.read_csv(T / 'panel_fe_event.csv')
    names = {'heavy_main': 'Heavy-AI main body (pts)', 'abs_flag': 'Abstract flag (pts)', 'within_lab_distance': 'Within-lab distance (x100)', 'school_centroid_distance': 'Distance to school centroid (x100)'}
    rows = ['| outcome | pre mean | post mean | S0 naive | S1 common trend | S2 PI trend (headline) | S2 both periods | S2 excl. partial | placebo 2020 S2 | pre-trend p |', '|---|---|---|---|---|---|---|---|---|---|']
    for o, lab in names.items():
        k = 100.0
        g = lambda smp, brk, spec: fmt(pick(t, outcome=o, sample=smp, brk=brk, spec=spec), k, 1 if o in SHARE else 2)  # noqa: E731
        base = pick(t, outcome=o, sample='all', brk='real', spec='S2_pi_trend')
        p = ev[(ev.outcome == o) & (ev.term == 'pretrend_wald') & (ev['sample'] == 'all') & (ev.brk == 'real')]
        rows.append(f'| {lab} | {k * base.pre_mean:.1f} | {k * base.post_mean:.1f} | {g("all", "real", "S0_pi_fe")} | {g("all", "real", "S1_common_trend")} | **{g("all", "real", "S2_pi_trend")}** | '
                    f'{g("balanced1", "real", "S2_pi_trend")} | {g("excl_partial", "real", "S2_pi_trend")} | {g("all", "fake2020", "S2_pi_trend")} | {p["p"].iloc[0]:.3f} |')
    n = pick(t, outcome='heavy_main', sample='all', brk='real', spec='S2_pi_trend')
    return '\n'.join(rows), f'heavy-AI: {int(n.n_obs)} paper rows, {int(n.n_pis)} PIs'


def design2(T):
    d = pd.read_csv(T / 'exposure_did.csv')
    rows = ['| outcome | exposure | main (school x year FE) | cross-fit exposure | + subfield x year | year FE only | excl. partial | placebo 2020 | pre-trend p | PIs |', '|---|---|---|---|---|---|---|---|---|---|']
    for o in ('heavy_main', 'abs_flag'):
        for x in ('style_distance', 'kobak_distance', 'lang_share', 'lang_share_wide', 'lang_share_team'):
            g = lambda cfg, smp, fe: fmt(pick(d, outcome=o, exposure=x, cfg=cfg, sample=smp, fe=fe), 100.0, 1)  # noqa: E731
            m = pick(d, outcome=o, exposure=x, cfg='main', sample='all', fe='school_year')
            rows.append(f'| {o} | {x} | **{g("main", "all", "school_year")}** | {g("crossfit", "all", "school_year")} | {g("main", "all", "school_topic_year")} | {g("main", "all", "year")} | '
                        f'{g("main", "excl_partial", "school_year")} | {g("placebo2020", "all", "school_year")} | {m.pretrend_p:.3f} | {int(m.n_pis)} |')
    return '\n'.join(rows)


def design3(T):
    e = pd.read_csv(T / 'revision_effects.csv')
    c = pd.read_csv(T / 'revision_cells.csv')
    rows = ['| kind | scope | pairs pre_pre / pre_post / post_post | mean change pre_pre | pre_post - pre_pre | post_post - pre_pre | placebo fake 2020 |', '|---|---|---|---|---|---|---|']
    for kind in ('A', 'S'):
        for scope in ('main', 'main_appendix'):
            q = e[(e.kind == kind) & (e.scope == scope) & (e.outcome == 'flagged_share') & (e['sample'] == 'all')]
            n = {r.cell: int(r.n) for r in c[c.kind == kind].itertuples()}
            g = lambda con, des='real': fmt(pick(q, contrast=con, design=des), 100.0, 2)  # noqa: E731
            rows.append(f'| {kind} | {scope} | {n.get("pre_pre")} / {n.get("pre_post")} / {n.get("post_post")} | {g("mean pre_pre")} | **{g("pre_post - pre_pre")}** | {g("post_post - pre_pre")} | {g("fake_cross - fake_pre", "fake2020")} |')
    return '\n'.join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--id', default='2026-11-08')
    a = ap.parse_args()
    res = C.results_dir(a.id) / 'designs'
    T = res / 'tables'
    parts = ['# Headline tables (generated by study_design_report.py; points = percentage points unless stated; intervals are 95% cluster-robust or cluster-bootstrap)\n']
    for title, fn in (('Design 1: PI panel with author fixed effects', design1), ('Design 2: exposure differences (effect of post-2023 x one SD of exposure)', design2), ('Design 3: within-paper arXiv revision (change in flagged share, final minus v1, points)', design3)):
        try:
            r = fn(T)
            parts.append(f'## {title}\n\n' + (r[0] + '\n\n' + r[1] if isinstance(r, tuple) else r) + '\n')
        except FileNotFoundError as e:
            parts.append(f'## {title}\n\nnot available: {e.filename}\n')
    (res / 'headline.md').write_text('\n'.join(parts))
    print('\n'.join(parts))


if __name__ == '__main__':
    main()
