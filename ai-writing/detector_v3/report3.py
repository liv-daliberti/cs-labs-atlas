"""Tables of the v3 validation (results/summary.json, results/tables.md) from eval3 on the saved logits.

models   v2 (the published detector, rescored on the v3 sets), v3 'all' (every family in training), and three leave-one-family-out
         models lofo-<family> (family held out of training; scored on that family's test-split outputs).
alpha    cal-set false-positive level that fixes each model's threshold: 0.3% (headline) and 1% (v2's own operating point).
ensemble v3 detector + Binoculars score + log words, logistic regression on cal only (a held-out family's cal outputs excluded).
No plot is drawn here; year series end at 2025 and the held-out real set covers 2016-2021 only.
usage: report3.py
"""
import json
import numpy as np
from sklearn.linear_model import LogisticRegression
import v3common as C
import eval3 as E

TAGS = ['v2', 'all', 'lofo-llama', 'lofo-gemma', 'lofo-qwen']
ALPHAS = (0.003, 0.01)


def bino_arrays():
    d = C.RESULTS / 'bino'
    out = {}
    for name in ('ai', 'cal_real', 'test_real'):
        parts, i = [], 0
        while (d / f'{name}-{i}.npy').exists():
            parts.append(np.load(d / f'{name}-{i}.npy')); i += 1
        out[name] = np.concatenate(parts) if parts else None
    return out


def ensemble(run, bino, hold=None):
    """A copy of `run` whose scores are the stacked (detector, Binoculars, log words) logit."""
    import copy
    r = copy.copy(run)
    f = lambda z, b, w: np.c_[z, b[:, 0], np.log(w)]  # noqa: E731
    wc, wt = run.arrs(run.mc, 'words'), run.arrs(run.mt, 'words')
    fam = np.array([x['family'] for x in run.ma]); sp = np.array([x['split'] for x in run.ma]); t = np.array([x['task'] for x in run.ma])
    wa = run.arrs(run.ma, 'words')
    fa = f(run.za, bino['ai'], wa)
    use = (sp == 'cal') & np.isin(t, E.CLAIM_TASKS) & (fam != hold if hold else True)
    X = np.r_[f(run.zc, bino['cal_real'], wc), fa[use]]; y = np.r_[np.zeros(len(run.zc)), np.ones(use.sum())]
    lr = LogisticRegression(C=10.0, max_iter=500, class_weight={0: 1.0, 1: 5.0}).fit(X, y)
    g = lambda A: lr.decision_function(A)  # noqa: E731
    r.zc, r.zt, r.za = g(f(run.zc, bino['cal_real'], wc)), g(f(run.zt, bino['test_real'], wt)), g(fa)
    r.zat, r.mat = np.zeros(0), []
    r.coef = lr.coef_.tolist()
    return r


def main():
    res = {}
    bino = bino_arrays()
    have_bino = all(v is not None for v in bino.values())
    for tag in TAGS:
        if not (C.RESULTS / tag / 'scores.npz').exists():
            continue
        run = E.Run(tag)
        for a in ALPHAS:
            res[f'{tag}@{a}'] = run.evaluate(a)
        if have_bino and tag != 'v2':
            hold = tag.split('-', 1)[1] if tag.startswith('lofo-') else None
            if len(bino['ai']) == len(run.za) and len(bino['test_real']) == len(run.zt):
                en = ensemble(run, bino, hold)
                for a in ALPHAS:
                    res[f'{tag}+bino@{a}'] = en.evaluate(a)
    json.dump(res, open(C.RESULTS / 'summary.json', 'w'), indent=1)
    L = ['# Detector v3 validation (generated by report3.py)', '']
    for a in ALPHAS:
        L += [f'## Threshold at cal FPR {100 * a:.1f}% (non-abstained passages)', '',
              '| model | FPR (95% CI) | abstain share | llama miss | gemma miss | qwen miss | phi | mistral | olmo | granite |', '|---|---|---|---|---|---|---|---|---|---|']
        for k, r in res.items():
            if not k.endswith(f'@{a}'):
                continue
            fam = r['family']
            cells = [E.fmtm(fam[f'{f}/claim']).split(' n=')[0] if f'{f}/claim' in fam else '' for f in ('llama', 'gemma', 'qwen', 'phi', 'mistral', 'olmo', 'granite')]
            L.append(f"| {k.split('@')[0]} | {E.fmt(r['fpr'])} | {100 * r['abstain_share_test']:.1f}% | " + ' | '.join(cells) + ' |')
        L.append('')
    for key in (f'all@{ALPHAS[0]}', f'v2@{ALPHAS[0]}'):
        if key in res:
            r = res[key]
            L += [f'## Per generator x task miss rate, {key}', '', '| generator/task | miss (95% CI) | n |', '|---|---|---|']
            for k, v in r['tpr'].items():
                L.append(f"| {k} | {100 * v['miss_rate']:.2f}% ({100 * v['miss_ci'][0]:.2f}-{100 * v['miss_ci'][1]:.2f}) | {v['n']} |")
            L += ['', f'FPR by year, {key}', '', '| year | flagged (95% CI) | n |', '|---|---|---|']
            for y, v in r['fpr_by_year'].items():
                L.append(f"| {y} | {E.fmt(v)} | {v['n']} |")
            L.append('')
    for tag in ('lofo-llama', 'lofo-gemma', 'lofo-qwen'):
        key = f'{tag}@{ALPHAS[0]}'
        if key in res:
            f = tag.split('-', 1)[1]
            L += [f'## {tag}: held-out family {f}, per task miss rate', '', '| task | miss (95% CI) | n |', '|---|---|---|']
            for t in E.CLAIM_TASKS + ('claim', 'partial'):
                v = res[key]['family'].get(f'{f}/{t}')
                if v:
                    L.append(f"| {t} | {100 * v['miss_rate']:.2f}% ({100 * v['miss_ci'][0]:.2f}-{100 * v['miss_ci'][1]:.2f}) | {v['n']} |")
            L.append('')
    open(C.RESULTS / 'tables.md', 'w').write('\n'.join(L))
    print('\n'.join(L[:60]))


if __name__ == '__main__':
    main()
